import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../../core/theme/app_colors.dart';
import '../../../core/theme/app_typography.dart';
import '../../../core/theme/app_spacing.dart';
import '../../../core/localization/locale_provider.dart';
import '../../../models/diagnosis_models.dart';
import '../../../models/advisory_models.dart';
import '../../../models/gate_models.dart';
import '../../../widgets/app_button.dart';
import '../../../widgets/app_card.dart';
import '../../../widgets/app_status_badge.dart';
import '../../../widgets/stub_banner.dart';
import '../../../widgets/advisory_ipm_card.dart';
import '../../../widgets/language_selector_button.dart';
import '../../../widgets/farmer_contextual_voice_action.dart';

/// Screen displayed when Confidence Gate outcome is 'advise' or Doubt Doctor is resolved.
class AdvisoryResultScreen extends ConsumerWidget {
  final DiagnoseResponse? response;
  final DiagnosisDetail? resolvedDiagnosis;
  final AdvisoryModel? resolvedAdvisory;
  final List<CitationModel>? resolvedCitations;
  final String? resolvedSpokenSummary;
  final GateDecision? gate;

  const AdvisoryResultScreen({
    super.key,
    this.response,
    this.resolvedDiagnosis,
    this.resolvedAdvisory,
    this.resolvedCitations,
    this.resolvedSpokenSummary,
    this.gate,
  });

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final strings = ref.watch(stringsProvider);

    final isStub = response?.gate.isStub ?? gate?.isStub ?? false;
    final diagnosis = response?.diagnosis ?? resolvedDiagnosis;
    final advisory = response?.advisory ?? resolvedAdvisory;
    final citations = response?.citations ?? resolvedCitations ?? [];
    final spokenSummary = response?.spokenSummary ?? resolvedSpokenSummary;
    final alternatives = response?.gate.alternatives ?? gate?.alternatives ?? [];

    // Convert models to AdvisoryIpmCard formats
    final ladderRungs = (advisory?.ladder ?? []).map((r) {
      return LadderRung(
        tier: r.tier,
        action: r.action,
        dosage: r.dosage,
        phiDays: r.phiDays,
        reentryHours: r.reentryHours,
      );
    }).toList();

    final citationItems = citations.map((c) {
      return AdvisoryCitation(
        docId: c.docId,
        title: c.title,
        reviewedOn: c.reviewedOn,
      );
    }).toList();

    return Scaffold(
      backgroundColor: AppColors.ricePaper,
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_rounded, color: AppColors.forest),
          tooltip: 'Back to Home',
          onPressed: () => Navigator.of(context).popUntil((route) => route.isFirst),
        ),
        title: Text(
          strings.diagnosisResultTitle,
          style: AppTypography.subheading.copyWith(
            color: AppColors.primaryDark,
            fontWeight: FontWeight.w700,
          ),
        ),
        actions: const [
          LanguageSelectorButton(),
        ],
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(AppSpacing.l20),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              // Stub mode banner if is_stub == true
              if (isStub) ...[
                const StubBanner(
                  message: 'Demonstration Mode: Vision model predictions are generated by mock engine.',
                ),
                const SizedBox(height: AppSpacing.m16),
              ],

              // Top Confident Diagnosis Summary Header
              AppCard(
                padding: const EdgeInsets.all(AppSpacing.l16),
                backgroundColor: AppColors.primaryLight.withValues(alpha: 0.4),
                border: Border.all(color: AppColors.forest.withValues(alpha: 0.3)),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Expanded(
                          child: Text(
                            strings.highConfidence,
                            style: AppTypography.caption.copyWith(
                              color: AppColors.forest,
                              fontWeight: FontWeight.w800,
                            ),
                          ),
                        ),
                        const SizedBox(width: AppSpacing.s8),
                        AppStatusBadge(
                          status: diagnosis?.severity ?? 'early',
                          type: StatusBadgeType.severity,
                        ),
                      ],
                    ),
                    const SizedBox(height: AppSpacing.s8),
                    Text(
                      diagnosis?.label.replaceAll('_', ' ').toUpperCase() ?? 'PADDY BLAST (भातावरील करपा)',
                      style: AppTypography.title.copyWith(
                        color: AppColors.primaryDark,
                        fontWeight: FontWeight.w800,
                      ),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: AppSpacing.l20),

              // Grounded Advisory with Mandatory IPM Ordering
              AdvisoryIpmCard(
                possibleIssue: advisory?.possibleIssue ?? 'Early Blast (भातावरील करपा - सुरुवातीची अवस्था)',
                whatToAvoid: advisory?.whatToAvoid ?? 'Do not top-dress nitrogen now. It accelerates spread.',
                whatToCheck: advisory?.whatToCheck ?? 'Diamond-shaped lesions with grey centres on upper leaves.',
                ladder: ladderRungs.isNotEmpty
                    ? ladderRungs
                    : [
                        const LadderRung(
                          tier: 'cultural',
                          action: 'Drain the field and let it dry for 48 hours.',
                        ),
                        const LadderRung(
                          tier: 'biological',
                          action: 'Apply Pseudomonas fluorescens as a foliar spray.',
                        ),
                        const LadderRung(
                          tier: 'chemical',
                          action: 'Tricyclazole 75 WP',
                          dosage: '0.6 g per litre',
                          phiDays: 30,
                          reentryHours: 24,
                        ),
                      ],
                expertTrigger: advisory?.expertTrigger,
                citations: citationItems,
                spokenSummary: spokenSummary,
                onPlayAudio: () {
                  ScaffoldMessenger.of(context).showSnackBar(
                    SnackBar(
                      content: Text(spokenSummary ?? 'Playing Marathi spoken advisory audio.'),
                      duration: const Duration(seconds: 2),
                    ),
                  );
                },
              ),
              const SizedBox(height: AppSpacing.l20),

              // Secondary Alternative Possibilities
              if (alternatives.isNotEmpty) ...[
                Text(
                  strings.otherPossibilities,
                  style: AppTypography.subheading.copyWith(
                    color: AppColors.soilCharcoal,
                    fontWeight: FontWeight.w700,
                  ),
                ),
                const SizedBox(height: AppSpacing.s8),
                ...alternatives.skip(1).map((alt) {
                  return Padding(
                    padding: const EdgeInsets.only(bottom: AppSpacing.s8),
                    child: AppCard(
                      padding: const EdgeInsets.symmetric(
                        horizontal: AppSpacing.l16,
                        vertical: AppSpacing.m12,
                      ),
                      child: Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          Text(
                            alt.label.replaceAll('_', ' ').toUpperCase(),
                            style: AppTypography.bodyMedium.copyWith(
                              fontWeight: FontWeight.w600,
                            ),
                          ),
                          Text(
                            '${(alt.confidence * 100).toStringAsFixed(0)}%',
                            style: AppTypography.bodySmall.copyWith(
                              color: AppColors.fieldSlate,
                              fontWeight: FontWeight.w600,
                            ),
                          ),
                        ],
                      ),
                    ),
                  );
                }),
                const SizedBox(height: AppSpacing.l20),
              ],

              // Contextual Voice Assistant Action (Level 2 Contextual)
              FarmerContextualVoiceAction.outline(
                label: strings.voiceContextDiagnosis,
                contextTopic: diagnosis?.label.replaceAll('_', ' ') ?? 'Crop Issue',
              ),
              const SizedBox(height: AppSpacing.m12),

              // Back to Home Button
              AppButton.primary(
                label: strings.backToHome,
                size: AppButtonSize.large,
                onPressed: () => Navigator.of(context).popUntil((route) => route.isFirst),
                leadingIcon: const Icon(Icons.home_rounded, color: Colors.white),
              ),
              const SizedBox(height: AppSpacing.l20),
            ],
          ),
        ),
      ),
    );
  }
}
